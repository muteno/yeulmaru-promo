def put(parent, el):
    """스키마 순서를 지켜 el을 parent에 넣는다(동명 태그는 교체)."""
    kind = parent.tag.split("}")[-1]
    order = SEQ[kind]
    name = el.tag.split("}")[-1]
    for old in parent.findall(qn("w:" + name)):
        parent.remove(old)
    idx = order.index(name)
    for child in parent:
        cn = child.tag.split("}")[-1]
        if cn not in order or order.index(cn) > idx:
            child.addprevious(el)
            return el
    parent.append(el)
    return el


def spacing(p, before=None, after=None, line=None, keep_next=False, keep_lines=False):
    pPr = p._p.get_or_add_pPr()
    if keep_next:
        put(pPr, _el("w:keepNext"))
    if keep_lines:
        put(pPr, _el("w:keepLines"))
    sp = _el("w:spacing")
    if before is not None:
        sp.set(qn("w:before"), str(before))
    if after is not None:
        sp.set(qn("w:after"), str(after))
    if line is not None:
        sp.set(qn("w:line"), str(line))
        sp.set(qn("w:lineRule"), "auto")
    put(pPr, sp)
    return p


def run(p, text, size=None, bold=False, color=None, italic=False):
    r = p.add_run(text)
    rf = r._r.get_or_add_rPr().get_or_add_rFonts()
    for a in ("w:ascii", "w:eastAsia", "w:hAnsi", "w:cs"):
        rf.set(qn(a), FONT)
    if size:
        r.font.size = Pt(size)
    r.bold = bold
    r.italic = italic
    if color:
        r.font.color.rgb = RGBColor.from_string(color)
    return r


def rich(p, chunks, size=None, color=C_BODY):
    """chunks = [(text, bold?), ...] — 한 문단 안에서 굵기만 갈아 끼운다."""
    for t, b in chunks:
        run(p, t, size=size, bold=b, color=color)
    return p


