def _el(tag, **kw):
    e = OxmlElement(tag)
    for k, v in kw.items():
        e.set(qn("w:" + k), str(v))
    return e


# ── OOXML은 자식 순서가 스키마로 고정돼 있다(순서 어기면 Word·LibreOffice가 파일을 못 연다).
#    아래 순서표대로 넣고, 같은 태그가 이미 있으면 갈아 끼운다.
